// One-time dev-time tool: reads the WooCommerce-export product CSV and emits
// seed.sql (INSERT statements) for the D1 `products` table.
//
// Usage:
//   node scripts/seed-products.mjs > seed.sql
//   wrangler d1 execute pinocchio --file=./seed.sql --remote
//
// Not deployed; re-run by hand whenever the menu changes and needs a full re-seed.

import { readFileSync, readdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");
const csvPath = path.join(root, "wp-theme", "pinocchio-termekek-import.csv");
const imagesDir = path.join(root, "images");

function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = "";
  let inQuotes = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (inQuotes) {
      if (c === '"') {
        if (text[i + 1] === '"') { field += '"'; i++; }
        else inQuotes = false;
      } else field += c;
    } else if (c === '"') {
      inQuotes = true;
    } else if (c === ",") {
      row.push(field);
      field = "";
    } else if (c === "\n" || c === "\r") {
      if (c === "\r" && text[i + 1] === "\n") i++;
      row.push(field);
      rows.push(row);
      row = [];
      field = "";
    } else {
      field += c;
    }
  }
  if (field.length || row.length) {
    row.push(field);
    rows.push(row);
  }
  return rows.filter((r) => r.some((f) => f !== ""));
}

function slugify(name) {
  return name
    .toLowerCase()
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "") // strip accents
    .replace(/'/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

function normalizeForMatch(name) {
  return name.toLowerCase().replace(/\s+/g, "").replace(/'/g, "");
}

const imageFiles = readdirSync(imagesDir).filter((f) => f.endsWith(".avif"));
const imageLookup = new Map();
for (const file of imageFiles) {
  const base = file.replace(/\.avif$/, "");
  imageLookup.set(normalizeForMatch(base), file);
}
// Known drift: CSV "4 Formaggi" -> file "4formaggi.avif" (no space).
imageLookup.set(normalizeForMatch("4 Formaggi"), "4formaggi.avif");

function findImage(name) {
  return imageLookup.get(normalizeForMatch(name)) || null;
}

const csvText = readFileSync(csvPath, "utf8");
const rows = parseCsv(csvText);
const header = rows[0];
const idx = Object.fromEntries(header.map((h, i) => [h.trim(), i]));

function sqlString(value) {
  if (value === null || value === undefined) return "NULL";
  return `'${String(value).replace(/'/g, "''")}'`;
}

const lines = [];
lines.push("-- Generated by scripts/seed-products.mjs — do not hand-edit, re-run the script instead.");
lines.push(
  "INSERT INTO products (slug, name, category, subcategory, description, price, is_spicy, image_file, is_modifier_eligible, is_available, sort_order) VALUES"
);

const values = [];
let sortOrder = 0;
let withImageCount = 0;
for (let r = 1; r < rows.length; r++) {
  const row = rows[r];
  if (!row || !row[idx["Name"]]) continue;

  const name = row[idx["Name"]].trim();
  const price = parseInt(row[idx["Regular price"]], 10);
  const categoriesRaw = row[idx["Categories"]].trim();
  const [category, subcategory] = categoriesRaw.split(">").map((s) => s && s.trim());
  const description = (row[idx["Short description"]] || "").trim() || null;
  const isSpicy = (row[idx["Tags"]] || "").trim() === "csípős" ? 1 : 0;
  const isModifierEligible = category === "Extra feltétek" ? 1 : 0;
  const slug = slugify(name);
  const imageFile = findImage(name);
  if (imageFile) withImageCount++;

  values.push(
    `(${sqlString(slug)}, ${sqlString(name)}, ${sqlString(category)}, ${sqlString(
      subcategory || null
    )}, ${sqlString(description)}, ${price}, ${isSpicy}, ${sqlString(
      imageFile
    )}, ${isModifierEligible}, 1, ${sortOrder})`
  );
  sortOrder++;
}

lines.push(values.join(",\n") + ";");
console.log(lines.join("\n"));

console.error(`Seeded ${values.length} products, ${withImageCount} with a matched image.`);
